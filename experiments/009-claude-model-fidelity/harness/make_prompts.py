"""Generate experiment 009's synthetic B2B prompt panel with claude-haiku-4-5.

Forty prompts: 20 software categories x 2 intents.

- ``shortlist``: a buyer states a concrete company profile (headcount,
  industry, one constraint) and asks for the best options or a shortlist.
- ``evaluate``: a buyer describes a use case and asks what the top options
  are and how they compare.

One Haiku call per (category, intent), first-person buyer phrasing, 15 to 45
words, no vendor or product names, no location, no year. Each draft is checked
by rule (:func:`validate`) and regenerated up to 3 times on failure. Item ids
are deterministic: ``b2b_01``..``b2b_40`` in category order, shortlist before
evaluate.

The prompts are synthetic, generated by us over categories rather than brands,
so they fall under the data policy's synthetic-study exemption. They still
live only under ``data/raw/`` until the release gate.

Usage (repo root):
    uv run python experiments/009-claude-model-fidelity/harness/make_prompts.py \
        [--env-file /Users/jcw/projects/spyglasses/.env.local]

Outputs: ``data/raw/prompts.csv`` (item_id, category, intent, text) and
``data/raw/generator/prompts_run.json`` (model, timestamps, every attempt).
"""

