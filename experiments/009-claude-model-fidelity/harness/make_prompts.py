LOCATION_TERMS = ("US", "USA", "U.S.", "UK", "EU", "Europe", "European", "America", "American",
                  "Canada", "Canadian", "Australia", "APAC", "EMEA", "LATAM")
LOCATION_PHRASES = re.compile(r"\b(based in|located in|headquartered in|offices in)\b", re.I)
#: Capitalized words allowed mid-sentence (acronyms are allowed separately).
ALLOWED_CAPS = frozenset({"I", "I'm", "I've", "I'd", "I'll", "SaaS", "DevOps", "FinTech",
                          "Series", "PhD", "IaaS", "PaaS", "HRIS", "ERP", "EDR"})
RECOMMEND_RE = re.compile(
    r"\b(best|recommend\w*|shortlist|short list|options?|compare|comparison|compares|top|"
    r"which|alternatives|choose|pick|stack up|versus|vs)\b",
    re.I,
)
YEAR_RE = re.compile(r"\b(19|20)\d\d\b")
_ACRONYM_RE = re.compile(r"^[A-Z0-9&/+\-]{2,7}s?$")


def _term_re(term: str) -> re.Pattern:
    # Case-sensitive: brands are proper nouns, and several are ordinary words in
    # lowercase ("sales teams", "outreach", "ramp up", "front desk").
    return re.compile(r"(?<![A-Za-z0-9])" + re.escape(term) + r"(?![A-Za-z0-9])")


def validate(text: str, category: str) -> list[str]:
    """Rule problems with a draft prompt; empty means it passes."""
    problems: list[str] = []
    words = text.split()
    if not MIN_WORDS <= len(words) <= MAX_WORDS:
        problems.append(f"word count {len(words)} outside {MIN_WORDS}-{MAX_WORDS}")
    for term in (*GLOBAL_BRANDS, *CATEGORY_BRANDS.get(category, ())):
        if _term_re(term).search(text):
            problems.append(f"brand term {term!r}")
    for term in LOCATION_TERMS:
        if re.search(r"(?<![A-Za-z])" + re.escape(term) + r"(?![A-Za-z])", text):
            problems.append(f"location term {term!r}")
    if LOCATION_PHRASES.search(text):
        problems.append("location phrase")
    if YEAR_RE.search(text):
        problems.append("contains a year")
    if not RECOMMEND_RE.search(text):
        problems.append("not a recommendation/comparison request")
    # Capitalized-token heuristic: a capitalized word that does not start a
    # sentence and is not an acronym is probably a proper noun (a brand).
    sentence_start = True
    for raw in words:
        token = raw.strip("\"'()[],;:")
        if token and token[0].isupper() and not sentence_start:
            core = token.rstrip(".?!")
            if core not in ALLOWED_CAPS and not _ACRONYM_RE.match(core.split("-")[0]):
                problems.append(f"capitalized token {core!r}")
        sentence_start = raw.endswith((".", "?", "!", ":"))
    return problems


# ------------------------------------------------------------ generation


def item_plan() -> list[dict]:
    rows = []
    n = 0
    for ci, category in enumerate(CATEGORIES):
        for intent in INTENTS:
            n += 1
            rows.append(
                {
                    "item_id": f"b2b_{n:02d}",
                    "category": category,
                    "intent": intent,
                    "size": SIZES[ci % len(SIZES)],
                    "industry": INDUSTRIES[(ci * 7) % len(INDUSTRIES)],
                }
            )
    return rows


def brief_for(row: dict) -> str:
    return BRIEFS[row["intent"]].format(
        category=row["category"], size=row["size"], industry=row["industry"]
    )


def generate_one(client, row: dict) -> tuple[str | None, list[dict], float]:
    attempts: list[dict] = []
    spent = 0.0
    feedback = ""
    for attempt in range(1, MAX_ATTEMPTS + 1):
        brief = brief_for(row) + feedback
        msg = client.messages.create(
            model=MODEL,
            max_tokens=400,
            system=SYSTEM_PROMPT,
            messages=[{"role": "user", "content": brief}],
            tools=[TOOL],
            tool_choice={"type": "tool", "name": "emit_prompt"},
        )
        usage = msg.usage.to_dict()
        spent += cost_from_usage(MODEL, usage)["total"]
        text = next(
            (b.input.get("prompt", "") for b in msg.content if b.type == "tool_use"), ""
        ).strip()
        text = " ".join(text.split())
        problems = validate(text, row["category"]) if text else ["empty"]
        attempts.append(
            {
                "attempt": attempt,
                "brief": brief,
                "text": text,
                "problems": problems,
                "model": msg.model,
                "usage": usage,
                "at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            }
        )
        if not problems:
            return text, attempts, spent
        feedback = (
            "\n\nYour previous draft broke these rules: " + "; ".join(problems)
            + ". Write a new prompt that follows every rule."
        )
    return None, attempts, spent


def parse_profiles(specs: list[str]) -> dict[str, tuple[str, str]]:
    """``["b2b_15=250-person|wholesale distributor"]`` -> {item: (size, industry)}."""
    out: dict[str, tuple[str, str]] = {}
    for spec in specs:
        item, _, rest = spec.partition("=")
        size, sep, industry = rest.partition("|")
        if not (item and sep and size.strip() and industry.strip()):
            raise SystemExit(f"bad --profile {spec!r}; expected item=size|industry")
        out[item.strip()] = (size.strip(), industry.strip())
    return out


def run_items(client, plan: list[dict]) -> tuple[list[dict], list[dict], list[str], float]:
    results, log, failures, spent = [], [], [], 0.0
    for row in plan:
        text, attempts, cost = generate_one(client, row)
        spent += cost
        log.append({**row, "attempts": attempts, "final": text})
        if text is None:
            failures.append(row["item_id"])
            print(f"  FAILED {row['item_id']} {row['category']}/{row['intent']}: "
                  f"{attempts[-1]['problems']}")
        else:
            results.append({k: row[k] for k in ("item_id", "category", "intent")} | {"text": text})
            if len(attempts) > 1:
                print(f"  {row['item_id']} passed on attempt {len(attempts)}")
    return results, log, failures, spent


def main() -> None:
    from anthropic_client import DEFAULT_ENV_FILE, make_client

    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--env-file", default=DEFAULT_ENV_FILE)
    ap.add_argument("--out", default=str(EXP / "data" / "raw" / "prompts.csv"))
    ap.add_argument("--run-log", default=str(EXP / "data" / "raw" / "generator" / "prompts_run.json"))
    ap.add_argument("--regenerate", default=None,
                    help="comma-separated item ids to regenerate in place in --out; the run "
                         "is appended to the run log's 'regenerations' list")
    ap.add_argument("--profile", action="append", default=[],
                    help="per-item shortlist profile override, item=size|industry "
                         "(e.g. 'b2b_15=250-person|wholesale distributor'); repeatable")
    a = ap.parse_args()

    profiles = parse_profiles(a.profile)
    plan = item_plan()
    known = {r["item_id"] for r in plan}
    unknown = sorted(set(profiles) - known)
    if unknown:
        raise SystemExit(f"--profile for unknown items {unknown}")
    for row in plan:
        if row["item_id"] in profiles:
            row["size"], row["industry"] = profiles[row["item_id"]]
            row["profile_override"] = True

    regen = [i.strip() for i in a.regenerate.split(",")] if a.regenerate else None
    if regen:
        bad = sorted(set(regen) - known)
        if bad:
            raise SystemExit(f"unknown item ids {bad}")
        plan = [r for r in plan if r["item_id"] in regen]
    elif profiles:
        raise SystemExit("--profile needs --regenerate (a full run would overwrite the panel)")

    client = make_client(a.env_file)
    started = datetime.now(timezone.utc).isoformat(timespec="seconds")
    results, log, failures, spent = run_items(client, plan)
    finished = datetime.now(timezone.utc).isoformat(timespec="seconds")
    log_path = Path(a.run_log)
    log_path.parent.mkdir(parents=True, exist_ok=True)

    if regen:
        # Append to the existing log and replace only the regenerated rows.
        data = json.loads(log_path.read_text()) if log_path.exists() else {}
        data.setdefault("regenerations", []).append({
            "model": MODEL,
            "started_at": started,
            "finished_at": finished,
            "items_requested": regen,
            "profile_overrides": {k: list(v) for k, v in profiles.items()},
            "cost_usd": round(spent, 4),
            "failures": failures,
            "items": log,
        })
        log_path.write_text(json.dumps(data, indent=1))
        with open(a.out, newline="") as f:
            rows = list(csv.DictReader(f))
        new = {r["item_id"]: r for r in results}
        rows = [new.get(r["item_id"], r) for r in rows]
        present = {r["item_id"] for r in rows}
        rows += [r for i, r in new.items() if i not in present]
    else:
        log_path.write_text(json.dumps(
            {
                "model": MODEL,
                "started_at": started,
                "finished_at": finished,
                "system_prompt": SYSTEM_PROMPT,
                "briefs": BRIEFS,
                "max_attempts": MAX_ATTEMPTS,
                "cost_usd": round(spent, 4),
                "failures": failures,
                "items": log,
            },
            indent=1,
        ))
        rows = results

    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    with open(a.out, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["item_id", "category", "intent", "text"])
        w.writeheader()
        w.writerows(rows)

    print(f"\n{len(results)} prompts written to {a.out} ({len(failures)} failed); "
          f"generator spend ${spent:.4f}\n")
    for r in results:
        print(f"{r['item_id']}  [{r['category']} / {r['intent']}]\n    {r['text']}")
    if failures:
        raise SystemExit(f"failed items: {failures}")


if __name__ == "__main__":
    main()
