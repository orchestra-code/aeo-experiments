"""Experiment 010, "best for" secondary metric (EXPLORATORY, exploration split).

Mirrors "Where AI picks you" in the platform: the best-for phrases the judge
attaches to a brand it RECOMMENDS (top choice or one of many). Two groupings:

- phrase: the platform's own grouping key, `normalizePhrase(phrase)`
  (computed by harness/bestfor_segments.mts normalize, so it is the TS
  function, not a port);
- segment: the phrase's use-case segment from a per-category taxonomy
  (bestfor_segments.mts taxonomy + classify).

Statuses per answer: (brand, phrase key) pairs and (brand, segment) pairs over
recommended brands. Retention is computed exactly as in 10_explore.py.

Steps:
  uv run python .../pipeline/11_bestfor_explore.py --gather   # phrases.json
  (tsx) bestfor_segments.mts normalize | taxonomy | classify --pass a | classify --pass b
  uv run python .../pipeline/11_bestfor_explore.py            # results/exploration_bestfor.md
"""

from __future__ import annotations

import argparse
import itertools
import json
from collections import Counter, defaultdict
from pathlib import Path

import numpy as np

EXP = Path(__file__).resolve().parents[1]
INTERIM = EXP / "data" / "interim"
RESULTS = EXP / "results"
RECOMMENDED = ("top_choice", "one_of_many")
DATASETS = ("chatgpt_consumer", "chatgpt_agency", "claude_b2b")
CLAUDE_PRIMARY_ARM = "ui_default"


def load_answers() -> list[dict]:
    with (INTERIM / "answers.jsonl").open() as f:
        return [json.loads(line) for line in f if line.strip()]


def bf_dir(split: str) -> Path:
    return EXP / "data" / "raw" / f"bestfor_{split}"


def gather(answers: list[dict], split: str) -> None:
    counts: dict[str, Counter] = defaultdict(Counter)
    for a in answers:
        for b, cat in a["cats"].items():
            if cat in RECOMMENDED:
                counts[a["category"]].update(a["best_for"].get(b, []))
    out = {c: [{"phrase": p, "count": n} for p, n in cnt.most_common()]
           for c, cnt in sorted(counts.items())}
    d = bf_dir(split)
    d.mkdir(parents=True, exist_ok=True)
    (d / "phrases.json").write_text(json.dumps(out, indent=1))
    print(f"{sum(len(v) for v in out.values())} distinct phrases in {len(out)} categories")


def statuses(a: dict, norm: dict, seg: dict) -> dict[str, set]:
    s = {"any": set(), "phrase": set(), "segment": set(), "segment_ng": set()}
    for b, cat in a["cats"].items():
        if cat not in RECOMMENDED:
            continue
        phrases = a["best_for"].get(b, [])
        if phrases:
            s["any"].add(b)
        for p in phrases:
            k = norm.get(p)
            if k:
                s["phrase"].add((b, k))
            g = seg.get(a["category"], {}).get(p)
            if g and g not in ("other", "unassigned"):
                s["segment"].add((b, g))
                if g != "general":
                    s["segment_ng"].add((b, g))
    return s


def retention(pairs, key: str) -> tuple[float, int]:
    num = den = 0
    for x, y in pairs:
        num += 2 * len(x[key] & y[key])
        den += len(x[key]) + len(y[key])
    return (num / den if den else float("nan")), den // 2


def boot_ci(pairs_by_item: dict, key: str, rng, n_boot: int = 2000) -> tuple[float, float]:
    items = list(pairs_by_item)
    stats = np.empty((len(items), 2))
    for i, it in enumerate(items):
        num = den = 0
        for x, y in pairs_by_item[it]:
            num += 2 * len(x[key] & y[key])
            den += len(x[key]) + len(y[key])
        stats[i] = (num, den)
    W = rng.multinomial(len(items), np.full(len(items), 1 / len(items)), size=n_boot)
    with np.errstate(invalid="ignore", divide="ignore"):
        r = (W @ stats[:, 0]) / (W @ stats[:, 1])
    r = r[~np.isnan(r)]
    return float(np.quantile(r, 0.05)), float(np.quantile(r, 0.95))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--gather", action="store_true")
    ap.add_argument("--split", default="explore")
    args = ap.parse_args()
    answers = load_answers()
    if args.gather:
        gather(answers, args.split)
        return

    d = bf_dir(args.split)
    norm = json.loads((d / "norm.json").read_text())
    taxonomy = json.loads((d / "taxonomy.json").read_text())
    seg_a = json.loads((d / "segments_a.json").read_text())
    seg_b = json.loads((d / "segments_b.json").read_text())
    rng = np.random.default_rng(20261003)

    lines = ["# Experiment 010: \"best for\" secondary metric (exploratory)\n",
             "Exploration split only. Generated by `pipeline/11_bestfor_explore.py`. "
             "Mirrors \"Where AI picks you\": best-for phrases on recommended brands.\n"]

    # Instrument: taxonomy size, coverage, classifier test-retest
    lines.append("## Instrument\n")
    n_seg = {c: len(v) for c, v in taxonomy.items()}
    lines.append(f"Segments per category (including \"general\"): "
                 f"{min(n_seg.values())} to {max(n_seg.values())} across {len(n_seg)} categories.\n")
    tot = agree = other = 0
    for c, m in seg_a.items():
        for p, g in m.items():
            tot += 1
            agree += seg_b.get(c, {}).get(p) == g
            other += g in ("other", "unassigned")
    lines.append(f"Classifier test-retest on {tot} distinct phrases: {100 * agree / tot:.0f}% "
                 f"same segment. Phrases left outside every segment (pass a): "
                 f"{100 * other / tot:.0f}%.\n")
    distinct_norm = len(set(norm.values()))
    lines.append(f"Distinct raw phrases {len(norm)}; distinct platform phrase keys "
                 f"(normalizePhrase) {distinct_norm}.\n")

    lines.append("## Retention: does a brand keep its \"best for\" in another run?\n")
    lines.append("Status = (brand, phrase key) or (brand, use-case segment), over recommended "
                 "brands. Same within-prompt pairs as the shortlist analysis. 90% prompt-level "
                 "cluster bootstrap.\n")
    lines.append("| Dataset | Pairs | Recommended with any best-for | Same phrase key "
                 "(as shipped) | Same use-case segment | Same segment, excluding \"general\" | "
                 "Segment, classifier pass b |")
    lines.append("|---|---|---|---|---|---|---|")
    for ds in DATASETS:
        sub = [a for a in answers if a["dataset"] == ds
               and (ds != "claude_b2b" or a["arm"] == CLAUDE_PRIMARY_ARM)]
        if not sub:
            continue
        st_a = {a["task_id"]: statuses(a, norm, seg_a) for a in sub}
        st_b = {a["task_id"]: statuses(a, norm, seg_b) for a in sub}
        groups = defaultdict(list)
        for a in sub:
            groups[a["item_id"]].append(a["task_id"])
        pairs_a = {it: [(st_a[x], st_a[y]) for x, y in itertools.combinations(ids, 2)]
                   for it, ids in groups.items()}
        pairs_b = {it: [(st_b[x], st_b[y]) for x, y in itertools.combinations(ids, 2)]
                   for it, ids in groups.items()}
        flat_a = [p for v in pairs_a.values() for p in v]
        flat_b = [p for v in pairs_b.values() for p in v]
        cells = []
        for key in ("any", "phrase", "segment", "segment_ng"):
            r, _ = retention(flat_a, key)
            lo, hi = boot_ci(pairs_a, key, rng)
            cells.append(f"{r:.2f} [{lo:.2f}, {hi:.2f}]")
        rb, _ = retention(flat_b, "segment")
        lines.append(f"| {ds} | {len(flat_a)} | " + " | ".join(cells) + f" | {rb:.2f} |")
    lines.append("")
    lines.append("Read across a row: a recommended brand nearly always gets some best-for "
                 "phrase; the question is whether it is the same one.\n")

    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "exploration_bestfor.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
