"""Experiment 010: precision planning for the confirmatory spec (exploration data).

For each planned contrast, draws simulated studies of the confirmatory size
(prompts resampled with replacement from the exploration prompts, each
keeping all its runs) and reports the spread of the estimate: the 90%
half-width is 1.645 x SD across draws. B2B ChatGPT and Gemini have no
exploration data; the Claude B2B exploration (3 runs per prompt) stands in,
which is conservative for an 11-wave design (fewer pairs per prompt).

Writes results/power.md.
"""

from __future__ import annotations

import itertools
import json
from collections import defaultdict
from datetime import date
from pathlib import Path

import numpy as np

EXP = Path(__file__).resolve().parents[1]
INTERIM = EXP / "data" / "interim"
RESULTS = EXP / "results"
N_SIM = 1000
SEED = 20261003


def load() -> list[dict]:
    out = []
    with (INTERIM / "answers.jsonl").open() as f:
        for line in f:
            a = json.loads(line)
            for k in ("M", "R", "T", "P1"):
                a[k] = set(a[k])
            a["Pk"] = set(a["Pk"])
            out.append(a)
    return out


def per_prompt_stats(ans: list[dict]) -> dict[str, np.ndarray]:
    """Per prompt: summed numerators and denominators for each contrast part."""
    groups = defaultdict(list)
    for a in ans:
        groups[a["item_id"]].append(a)
    keys = ["R", "Pk", "T", "P1", "TR", "R_near", "R_far"]
    rows = []
    for runs in groups.values():
        acc = dict.fromkeys([f"{k}_{p}" for k in keys for p in ("num", "den")], 0.0)
        for x, y in itertools.combinations(runs, 2):
            for k in ("R", "Pk", "T", "P1"):
                acc[f"{k}_num"] += 2 * len(x[k] & y[k])
                acc[f"{k}_den"] += len(x[k]) + len(y[k])
            acc["TR_num"] += len(x["T"] & y["R"]) + len(y["T"] & x["R"])
            acc["TR_den"] += len(x["T"]) + len(y["T"])
            lag = abs((date.fromisoformat(x["run_date"]) - date.fromisoformat(y["run_date"])).days)
            if lag <= 2:
                acc["R_near_num"] += 2 * len(x["R"] & y["R"])
                acc["R_near_den"] += len(x["R"]) + len(y["R"])
            if lag >= 15:
                acc["R_far_num"] += 2 * len(x["R"] & y["R"])
                acc["R_far_den"] += len(x["R"]) + len(y["R"])
        rows.append([acc[f"{k}_{p}"] for k in keys for p in ("num", "den")])
    arr = np.array(rows)
    return {k: arr[:, 2 * i:2 * i + 2] for i, k in enumerate(keys)}


def ratio(nd: np.ndarray, w: np.ndarray) -> np.ndarray:
    with np.errstate(invalid="ignore", divide="ignore"):
        return (w @ nd[:, 0]) / (w @ nd[:, 1])


def simulate(stats: dict[str, np.ndarray], n_target: int, rng) -> dict[str, tuple[float, float]]:
    n = len(next(iter(stats.values())))
    w = rng.multinomial(n_target, np.full(n, 1 / n), size=N_SIM).astype(float)
    r = {k: ratio(v, w) for k, v in stats.items()}
    contrasts = {
        "H1 shortlist minus exact position": r["R"] - r["Pk"],
        "H2 shortlist minus top choice": r["R"] - r["T"],
        "H3 top choice minus rank 1": r["T"] - r["P1"],
        "H4 top choice still shortlisted": r["TR"],
        "H5 drift (15+ days minus 0-2 days)": r["R_far"] - r["R_near"],
    }
    full = np.ones((1, n))
    point = {
        "H1 shortlist minus exact position": ratio(stats["R"], full) - ratio(stats["Pk"], full),
        "H2 shortlist minus top choice": ratio(stats["R"], full) - ratio(stats["T"], full),
        "H3 top choice minus rank 1": ratio(stats["T"], full) - ratio(stats["P1"], full),
        "H4 top choice still shortlisted": ratio(stats["TR"], full),
        "H5 drift (15+ days minus 0-2 days)": ratio(stats["R_far"], full) - ratio(stats["R_near"], full),
    }
    out = {}
    for k, v in contrasts.items():
        v = v[~np.isnan(v)]
        out[k] = (float(point[k][0]), 1.645 * float(np.std(v)) if len(v) > 10 else float("nan"))
    return out


def main() -> None:
    ans = load()
    rng = np.random.default_rng(SEED)
    plans = [
        ("chatgpt_consumer holdout (95 prompts x 17 runs)", "chatgpt_consumer", None, 95),
        ("claude_b2b holdout, ui_default (26 prompts x 3 runs)", "claude_b2b", "ui_default", 26),
        ("new B2B collection, per platform (40 prompts; Claude B2B as proxy)", "claude_b2b",
         "ui_default", 40),
    ]
    lines = ["# Experiment 010: precision planning (exploration data)\n",
             "Point = exploration estimate. Half-width = projected 90% half-width at the "
             f"confirmatory size ({N_SIM} simulated studies, prompts resampled with "
             "replacement). Generated by `pipeline/12_power.py`.\n"]
    for label, ds, arm, n_target in plans:
        sub = [a for a in ans if a["dataset"] == ds and (arm is None or a["arm"] == arm)]
        res = simulate(per_prompt_stats(sub), n_target, rng)
        lines.append(f"## {label}\n")
        lines.append("| Contrast | Exploration point | Projected 90% half-width |\n|---|---|---|")
        for k, (pt, hw) in res.items():
            lines.append(f"| {k} | {pt:+.3f} | {hw:.3f} |")
        lines.append("")
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "power.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
